#!/usr/bin/env python3
"""Generate native and extension catalogs from the shared Korean/English source."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def outputs():
    catalog = json.loads((ROOT / 'localization/strings.json').read_text())
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    swift = '// Generated by scripts/sync_localization.py. Edit localization/strings.json.\n'
    swift += 'enum Translations {\n    static let english: [String: String] = [\n'
    swift += ''.join('        ' + quote(key) + ': ' + quote(value) + ',\n' for key, value in catalog.items())
    swift += '    ]\n}\n'
    javascript = '// Generated by scripts/sync_localization.py. Edit localization/strings.json.\nconst CHECKER_STRINGS = '
    javascript += json.dumps(catalog, ensure_ascii=False, indent=2) + ';\n'
    result = {ROOT / 'Sources/CheckerCore/GeneratedTranslations.swift': swift, ROOT / 'extension/strings.js': javascript}
    for language in ['en', 'ko']:
        translate = lambda value: catalog[value] if language == 'en' else value
        messages = {'extensionName': {'message': 'Checker — ' + translate('나중에 챙길 일')},
                    'extensionDescription': {'message': translate('현재 화면을 AI가 읽고 할 일·메모·카테고리를 만들어 Checker에 추가합니다.')},
                    'actionTitle': {'message': translate('Checker에 추가')}}
        result[ROOT / 'extension/_locales' / language / 'messages.json'] = json.dumps(messages, ensure_ascii=False, indent=2) + '\n'
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit('Localization output is stale: ' + str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


if __name__ == '__main__':
    main()
